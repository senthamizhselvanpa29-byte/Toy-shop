-- Toy Shop · Milestone 10: toy and category names in Tamil and Hindi.
-- Run once in Supabase → SQL Editor, after 0006_order_management.sql. Safe to run again.
--
-- Each toy and category gets a "translations" box:
--   { "ta": { "name": "…", "short_description": "…", "description": "…" },
--     "hi": { "name": "…", … } }
-- Anything left empty simply shows the English text.

alter table public.products
  add column if not exists translations jsonb not null default '{}'::jsonb;
alter table public.categories
  add column if not exists translations jsonb not null default '{}'::jsonb;

do $$
begin
  if not exists (select 1 from pg_constraint where conname = 'products_translations_is_object') then
    alter table public.products
      add constraint products_translations_is_object check (jsonb_typeof(translations) = 'object');
  end if;
  if not exists (select 1 from pg_constraint where conname = 'categories_translations_is_object') then
    alter table public.categories
      add constraint categories_translations_is_object check (jsonb_typeof(translations) = 'object');
  end if;
end $$;

